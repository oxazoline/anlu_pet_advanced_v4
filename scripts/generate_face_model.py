"""Generate synthesizable synchronous ROMs from pinned OpenCV XML."""
from pathlib import Path
import hashlib,json
from face_reference import load_model
ROOT=Path(__file__).resolve().parents[1]
stages,nodes=load_model();profile_stages,profile_nodes=load_model(True)
hdl=ROOT/'user_source/hdl_source'
def rom(name,width,depth,addr,values):
    s=f'// Generated by scripts/generate_face_model.py; do not hand-edit.\nmodule {name}(input wire I_clk,input wire [{addr-1}:0] I_addr,output reg [{width-1}:0] O_data);\n'
    s+=f'    reg [{width-1}:0] memory[0:{depth-1}];\n    integer n;\n    initial begin\n'
    s+=f'        for(n=0;n<{depth};n=n+1)memory[n]=0;\n'
    for i,v in enumerate(values):s+=f"        memory[{i}]={width}'h{v:0{(width+3)//4}x};\n"
    s+='    end\n    always @(posedge I_clk)O_data<=memory[I_addr];\nendmodule\n'
    (hdl/(name+'.v')).write_text(s,encoding='ascii')
features=[];subsets=[]
for rect,subset,leaves in nodes:
    v=0
    for coordinate in rect:v=(v<<5)|coordinate
    for leaf in leaves:v=(v<<14)|(round(leaf*4096)&0x3fff)
    features.append(v);subsets.extend(subset)
front_features=features.copy();features.extend([0]*(256-len(features)))
front_subsets=subsets.copy();subsets.extend([0]*(2048-len(subsets)))
for rect,subset,leaves in profile_nodes:
    v=0
    for coordinate in rect:
        assert 0<=coordinate<32
        v=(v<<5)|coordinate
    for leaf in leaves:v=(v<<14)|(round(leaf*4096)&0x3fff)
    features.append(v);subsets.extend(subset)
rom('ext_face_feature_rom',48,512,9,features)
rom('ext_face_subset_rom',32,4096,12,subsets)
s='// Q12 stages; profile input appended for source compatibility.\nmodule ext_face_stage_rom(input wire [4:0] I_stage,output reg [7:0] O_end,output reg signed [17:0] O_threshold,input wire I_profile);\n    always @(*)begin\n    O_end=0;O_threshold=0;\n    if(I_profile)case(I_stage)\n'
for i,(end,threshold) in enumerate(profile_stages):
    s+=f"        5'd{i}:begin O_end=8'd{end-1};O_threshold=18'sh{round(threshold*4096)&0x3ffff:05x};end\n"
s+='        default:begin end\n    endcase else case(I_stage)\n'
for i,(end,threshold) in enumerate(stages):
    s+=f"        5'd{i}:begin O_end=8'd{end-1};O_threshold=18'sh{round(threshold*4096)&0x3ffff:05x};end\n"
s+='        default:begin end\n    endcase\n    end\nendmodule\n'
(hdl/'ext_face_stage_rom.v').write_text(s,encoding='ascii')
(ROOT/'reports/face_model.json').write_text(json.dumps({'source':'OpenCV 4.10.0 lbpcascade_frontalface.xml','xml_sha256':hashlib.sha256((ROOT/'models/lbpcascade_frontalface.xml').read_bytes()).hexdigest(),'frontal_stages':20,'frontal_weak':139,'profile_stages':16,'profile_weak':130,'feature_rom':[512,48],'subset_rom':[4096,32],'fixed_point':'Q12 rounded, signed 14-bit leaves, signed 18-bit accumulator','scale_approximation':'scale feature x/y/w/h with quarter-step integer rounding; not identical to OpenCV resized-image pyramid'},indent=2))
print('Generated full 20-stage / 139-weak LBP model ROMs.')
